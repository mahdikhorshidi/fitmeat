/** انتخاب پایدار بر اساس تاریخ: در طول یک روز تغییر نمی‌کند */
function pick(list, salt) {
  const d = new Date();
  const key = d.getFullYear() * 372 + d.getMonth() * 31 + d.getDate() + salt;
  return list[key % list.length];
}

/** تشخیص ساده از نام و عضلات روز، برای همسو کردن توصیه با تمرین امروز */
function focusOf(day) {
  const text = `${day?.name || ''} ${(day?.blocks || []).flatMap(b => b.exercises.map(e => e.muscle || '')).join(' ')}`;
  if (/هواز|کاردیو|تردمیل|دو|اینتروال/.test(text)) return 'cardio';
  if (/پا|اسکات|ران|همسترینگ|ساق|باسن/.test(text)) return 'legs';
  if (/کشش|ریکاور|استراحت|تحرک/.test(text)) return 'recovery';
  return 'upper';
}


const ZWNJ = /‌/g;
export function normalize(s) {
  return String(s ?? '')
    .replace(ZWNJ, ' ')
    .replace(/[يى]/g, 'ی').replace(/ك/g, 'ک')
    .replace(/[ً-ْٰ]/g, '')
    .replace(/[ـ]/g, '')
    .replace(/[()«»"',.\-_/\\]/g, ' ')
    .replace(/\s+/g, ' ')
    .trim().toLowerCase();
}

const INDEX = (() => {
  const m = new Map();
  EXERCISES.forEach(ex => {
    [ex.fa, ...(ex.alias || [])].forEach(n => m.set(normalize(n), ex));
  });
  return m;
})();

/** حدس الگو از روی کلمات نام، وقتی حرکت در دانش‌نامه نیست */
const KEYWORDS = [
  [/پرس سینه|پرس سرشانه|پرس بالا|پرس زیر|شنا/, null],
  [/بالاسینه|بالا سینه|شیبدار/, 'ipress'],
  [/سرشانه|نظامی|بالای سر|اورهد/, 'vpress'],
  [/پرس پا/, 'legpress'],
  [/پرس/, 'hpress'],
  [/قفسه|فلای|کراس/, 'fly'],
  [/بارفیکس|لت|پول ?داون|زیربغل سیم|کشش عمودی/, 'vpull'],
  [/زیربغل|پارویی|قایقی|رو(ئ|ی)ینگ|row/, 'hrow'],
  [/نشر/, 'raise'],
  [/کول|شراگ/, 'shrug'],
  [/جلوبازو|جلو بازو|بایسپس|curl/, 'curl'],
  [/پشت ?بازو|تراپس|دیپ|پوش ?داون/, 'ext'],
  [/جلو ?پا/, 'legext'],
  [/پشت ?پا|همسترینگ/, 'legcurl'],
  [/ساق/, 'calf'],
  [/اسکات|هک/, 'squat'],
  [/لانج|اسپلیت|قدم/, 'lunge'],
  [/ددلیفت|رومانیایی|صبح ?بخیر|هیپ|لگن|پل/, 'hinge'],
  [/پلانک|کوه ?نورد|plank/, 'plank'],
  [/شکم|کرانچ|دراز ?نشست|زیرشکم/, 'crunch'],
  [/کشش|استرچ|حرکات اصلاحی|فوم/, 'stretch'],
  [/تردمیل|دویدن|دوچرخه|الپتیکال|روئینگ|هوازی|کاردیو|طناب/, 'cardio'],
];

export function guessPattern(name, mode) {
  const n = normalize(name);
  if (mode === 'cardio') return 'cardio';
  for (const [rx, pat] of KEYWORDS) {
    if (rx.test(n) && pat) return pat;
  }
  if (/پرس/.test(n)) return 'hpress';
  return mode === 'time' ? 'plank' : 'generic';
}

/** بهترین تطبیق برای یک نام حرکت؛ اگر نبود، ورودی «تخمینی» می‌سازد */
export function lookup(name, { muscle = '', mode = 'reps', equipment = '' } = {}) {
  const n = normalize(name);
  const exact = INDEX.get(n);
  if (exact) return { ...exact, match: 'exact' };

  // تطبیق جزئی: نام حرکت شامل نام دانش‌نامه‌ای باشد یا برعکس
  let best = null, score = 0;
  INDEX.forEach((ex, key) => {
    if (!key) return;
    if (n.includes(key) || key.includes(n)) {
      const s = Math.min(key.length, n.length) / Math.max(key.length, n.length);
      if (s > score) { score = s; best = ex; }
    }
  });
  if (best && score >= 0.5) return { ...best, match: 'near' };

  const pattern = guessPattern(name, mode);
  const template = EXERCISES.find(e => e.pattern === pattern);
  return {
    id: `guess:${pattern}`,
    fa: name,
    pattern,
    equip: equipment || template?.equip || '',
    primary: template?.primary || {},
    secondary: template?.secondary || {},
    stabil: template?.stabil || [],
    setup: [], exec: [], mistakes: [], breath: '',
    match: 'guess',
    guessedFrom: template?.fa || '',
  };
}

/** حرکات هم‌الگو برای جایگزینی امن */
export function substitutesFor(ex, { excludeName = '' } = {}) {
  const src = lookup(ex.name || ex.fa, ex);
  const nx = normalize(excludeName || ex.name || '');
  return EXERCISES
    .filter(c => c.pattern === src.pattern && normalize(c.fa) !== nx)
    .map(c => ({ ...c, why: whySafe(src, c) }));
}

function primaryKey(ex) {
  const [k] = Object.entries(ex.primary || {}).sort((a, b) => b[1] - a[1])[0] || [];
  return k;
}

function whySafe(src, cand) {
  const same = primaryKey(src) === primaryKey(cand);
  const bits = ['همان الگوی حرکتی'];
  bits.push(same ? 'همان عضلهٔ اصلی' : 'عضلهٔ اصلی کمی متفاوت');
  if (cand.equip && cand.equip !== src.equip) bits.push(`با ${cand.equip}`);
  return bits.join(' · ');
}

/**
 * ضریب پیشنهادی وزنه هنگام جایگزینی؛ تخمینی و محافظه‌کارانه.
 * منبع رویکرد: توصیهٔ NSCA برای شروع محافظه‌کارانه در تغییر ابزار/دامنه.
 */
export function loadFactor(from, to) {
  const kind = e => {
    const q = `${e.equip || ''}`;
    if (/بدن/.test(q)) return 'bw';
    if (/دستگاه/.test(q)) return 'machine';
    if (/دمبل/.test(q)) return 'db';
    if (/هالتر/.test(q)) return 'bb';
    return 'other';
  };
  const a = kind(from), b = kind(to);
  if (a === b) return { f: 1, note: 'وزنه را بدون تغییر نگه دار.' };
  if (a === 'bb' && b === 'db') return { f: 0.4, note: 'نسخهٔ دمبل: حدود ۴۰٪ وزنهٔ هالتر برای هر دمبل.' };
  if (a === 'db' && b === 'bb') return { f: 2.2, note: 'نسخهٔ هالتر: حدود دو برابر مجموع دمبل‌ها، اما یک ست سبک تست بزن.' };
  if (b === 'machine') return { f: 1, note: 'روی دستگاه با وزنهٔ سبک‌تر شروع کن تا مسیر حرکت را بشناسی.' };
  if (b === 'bw') return { f: 0, note: 'با وزن بدن است؛ تعداد تکرار را تا رسیدن به همان سختی تنظیم کن.' };
  return { f: 0.85, note: 'یک ست تست سبک بزن و بعد وزنه را تنظیم کن.' };
}
